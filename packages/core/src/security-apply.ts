// The fix-apply step (ADR-274): take a security card's proposed fix.action (G2,
// advisories/fix-action.ts) and apply it to the manifest and lockfile, then
// re-verify with scan_diff (G1, security-diff.ts) that the card's advisory is
// gone and no new one was introduced. This is the line between NEAT flagging a
// vulnerability and NEAT fixing it.
//
// The lockfile write is the remediation exception to the "lockfiles never
// written" rule (ADR-047): extraction and instrumentation still never touch a
// lockfile; this deliberate, user-or-agent-triggered fix does.
//
// How the fix is made:
// - The manifest edit is deterministic: a direct dependency's spec moves to the
//   fixed version (keeping its range operator), and a transitive one is pinned
//   through an npm `override`, which needs no parent resolution.
// - The lockfile is then regenerated by npm's own resolver
//   (`npm install --package-lock-only --ignore-scripts`), so the result is a
//   complete, consistent, `npm ci`-installable lockfile with correct integrity
//   and the dependency's own subtree. A hand-edited version field would clear
//   the CVE but leave a lockfile that will not install when a bump changes the
//   dependency's own dependencies; a fix that will not install is not a fix.
//   `--package-lock-only` writes no node_modules and `--ignore-scripts` runs no
//   install scripts, so no third-party code executes here.
//
// Scope: npm only in v0 (PyPI and Go follow); the security axis only (scan_diff
// re-verifies the vulnerability set, the project's own tests are the separate
// 0-regression check); and only `bump-to-fixedIn`. `remove-or-replace` has no
// deterministic target (a breaking bump or no fix at all), so it is reported,
// never guessed, and a caller never reads "not handled" as "fixed".

import { promises as fs } from 'node:fs'
import { execFileSync } from 'node:child_process'
import path from 'node:path'
import type { SecurityCard, SecurityDiff, SecurityFixAction } from '@neat.is/types'
import { scanDiffLocal, type ScanDiffOptions } from './security-diff.js'

export interface FileEdit {
  // Repo-relative path of the edited file.
  file: string
  change: 'manifest-spec' | 'manifest-override' | 'lockfile-regenerated'
  dependency: string
  from: string
  to: string
}

export type ApplyOutcome =
  | { applied: true; action: SecurityFixAction; edits: FileEdit[] }
  | { applied: false; action?: SecurityFixAction; reason: string }

export interface ApplyOptions {
  // The repo-relative directory that holds package.json / package-lock.json.
  // Default: the directory of the card's dependency.manifest.file.
  manifestDir?: string
  // Regenerate the lockfile after the manifest edit. Default: npm
  // install --package-lock-only --ignore-scripts in the manifest directory.
  // Injected so the manifest edit is unit-tested without invoking npm.
  regenerateLock?: (manifestDirAbs: string) => void | Promise<void>
}

interface PackageJson {
  dependencies?: Record<string, string>
  devDependencies?: Record<string, string>
  optionalDependencies?: Record<string, string>
  overrides?: Record<string, string>
  [k: string]: unknown
}

interface LockPkg {
  version?: string
  [k: string]: unknown
}

interface LockFile {
  packages?: Record<string, LockPkg>
  [k: string]: unknown
}

const DIRECT_FIELDS = ['dependencies', 'devDependencies', 'optionalDependencies'] as const
const hasOwn = (o: object, k: string) => Object.prototype.hasOwnProperty.call(o, k)

function npmRegenerate(manifestDirAbs: string): void {
  execFileSync('npm', ['install', '--package-lock-only', '--ignore-scripts', '--no-audit', '--no-fund'], {
    cwd: manifestDirAbs,
    stdio: 'ignore',
  })
}

// Keep the user's range operator (^, ~, >=, exact pin) and move only the version,
// so an applied fix reads like the bump a maintainer would have made.
function bumpSpec(prev: string, to: string): string {
  const op = (/^[\^~>=< ]+/.exec(prev) ?? [''])[0].trim()
  return `${op}${to}`
}

// The resolved version of a package in the lockfile (the first copy found),
// used only to skip a dependency already at the target.
function lockVersion(lock: LockFile, name: string): string | undefined {
  for (const [loc, meta] of Object.entries(lock.packages ?? {})) {
    if ((loc.startsWith('node_modules/') || loc.includes('/node_modules/')) && meta && typeof meta === 'object') {
      if (loc.slice(loc.lastIndexOf('node_modules/') + 'node_modules/'.length) === name && meta.version) return meta.version
    }
  }
  return undefined
}

/**
 * Apply a card's fix to the working tree. Edits the manifest deterministically
 * and regenerates the lockfile with npm. Returns applied:false with a reason for
 * anything it will not fix, so a caller never reads "not handled" as "fixed".
 */
export async function applyFixAction(scanPath: string, card: SecurityCard, opts: ApplyOptions = {}): Promise<ApplyOutcome> {
  const action = card.fix.action
  const dep = card.dependency
  if (!action) return { applied: false, reason: 'the card carries no fix action' }
  if (action.kind !== 'bump-to-fixedIn') {
    const major = action.majorTo ? `; a fix exists at ${action.majorTo}, but it is a breaking bump` : ''
    return { applied: false, action, reason: `fix is ${action.kind}: ${action.reason}${major}` }
  }
  if (dep.ecosystem !== 'npm') {
    return { applied: false, action, reason: `ecosystem ${dep.ecosystem} is not supported yet (npm only in v0)` }
  }

  const manifestDir = opts.manifestDir ?? path.dirname(dep.manifest.file)
  const pkgRel = path.join(manifestDir, 'package.json')
  const lockRel = path.join(manifestDir, 'package-lock.json')
  const dirAbs = path.resolve(scanPath, manifestDir)
  const pkgAbs = path.resolve(scanPath, pkgRel)
  const lockAbs = path.resolve(scanPath, lockRel)

  let pkg: PackageJson
  try {
    pkg = JSON.parse(await fs.readFile(pkgAbs, 'utf8')) as PackageJson
  } catch {
    return { applied: false, action, reason: `could not read package.json at ${pkgRel}` }
  }
  let before: string | undefined
  try {
    before = lockVersion(JSON.parse(await fs.readFile(lockAbs, 'utf8')) as LockFile, dep.name)
  } catch {
    return { applied: false, action, reason: `could not read package-lock.json at ${lockRel}` }
  }
  if (before === action.to) return { applied: false, action, reason: `already at ${action.to}` }

  const edits: FileEdit[] = []
  const directField = DIRECT_FIELDS.find((f) => pkg[f] && hasOwn(pkg[f] as object, dep.name))
  if (directField) {
    const field = pkg[directField] as Record<string, string>
    const prev = String(field[dep.name])
    const next = bumpSpec(prev, action.to)
    if (next !== prev) {
      field[dep.name] = next
      edits.push({ file: pkgRel, change: 'manifest-spec', dependency: dep.name, from: prev, to: next })
    }
  } else {
    pkg.overrides = pkg.overrides ?? {}
    const prev = pkg.overrides[dep.name] !== undefined ? String(pkg.overrides[dep.name]) : ''
    if (prev !== action.to) {
      pkg.overrides[dep.name] = action.to
      edits.push({ file: pkgRel, change: 'manifest-override', dependency: dep.name, from: prev, to: action.to })
    }
  }
  await fs.writeFile(pkgAbs, `${JSON.stringify(pkg, null, 2)}\n`)

  // Regenerate the lockfile so it is complete and installable, not just version-bumped.
  await (opts.regenerateLock ?? npmRegenerate)(dirAbs)
  edits.push({ file: lockRel, change: 'lockfile-regenerated', dependency: dep.name, from: before ?? '', to: action.to })

  return { applied: true, action, edits }
}

export interface DepApplyResult {
  dependencyId: string
  // The manifest.file the deduped cards shared.
  manifest: string
  outcome: ApplyOutcome
}

/**
 * Apply the fixes for a set of cards, once per (dependency, manifest). After the
 * reconcile step every card of a dependency carries the same fix.action, and
 * there are several cards per dependency (one per service and advisory), so a
 * naive per-card loop would apply the same bump many times. This dedups by
 * (dependency.id, manifest.file) and applies each dependency's bump once, in a
 * stable order. Each card derives its own manifest location from the card, so a
 * dependency in two services edits each service's manifest.
 */
export async function applyFixes(
  scanPath: string,
  cards: SecurityCard[],
  opts: Pick<ApplyOptions, 'regenerateLock'> = {},
): Promise<DepApplyResult[]> {
  const seen = new Map<string, SecurityCard>()
  for (const c of cards) {
    const key = `${c.dependency.id}\u0000${c.dependency.manifest.file}`
    if (!seen.has(key)) seen.set(key, c)
  }
  const out: DepApplyResult[] = []
  for (const key of [...seen.keys()].sort()) {
    const c = seen.get(key)!
    out.push({ dependencyId: c.dependency.id, manifest: c.dependency.manifest.file, outcome: await applyFixAction(scanPath, c, opts) })
  }
  return out
}

export interface ReverifyResult {
  outcome: ApplyOutcome
  // Present only when the fix was applied.
  reverify?: SecurityDiff
  // The card's advisory is gone (in `removed`) and the change introduced none.
  cleared?: boolean
}

/**
 * Apply the card's fix to the working tree, then scan_diff HEAD (the committed,
 * still-vulnerable state) against the working tree. `cleared` is true when the
 * card's advisory moved to `removed` and no new finding was introduced. Security
 * axis only; the project's own tests are the separate 0-regression check.
 */
export async function applyAndReverify(
  scanPath: string,
  card: SecurityCard,
  opts: ApplyOptions & ScanDiffOptions = {},
): Promise<ReverifyResult> {
  const { manifestDir, regenerateLock, ...scanOpts } = opts
  const applyOpts: ApplyOptions = { ...(manifestDir ? { manifestDir } : {}), ...(regenerateLock ? { regenerateLock } : {}) }
  const outcome = await applyFixAction(scanPath, card, applyOpts)
  if (!outcome.applied) return { outcome }
  const reverify = await scanDiffLocal(scanPath, { base: 'HEAD' }, scanOpts)
  const cleared = reverify.removed.some((e) => e.advisoryId === card.advisory.id) && reverify.introduced.length === 0
  return { outcome, reverify, cleared }
}
